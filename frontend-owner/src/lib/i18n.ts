export function useTranslation() {
  const [lang, setLangState] = useState<LanguageCode>(getInitialLanguage);

  useEffect(() => {
    const handler = (e: any) => {
      setLangState(e.detail || getInitialLanguage());
    };
    window.addEventListener("redo_lang_changed", handler);
    return () => window.removeEventListener("redo_lang_changed", handler);
  }, []);

  const t = (key: string): string => {
    return TRANSLATIONS[lang]?.[key] || TRANSLATIONS.en[key] || key;
  };

  return { t, lang };
}
